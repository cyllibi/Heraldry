#!/usr/bin/env python3
"""Build Heraldry/CREDITS.md from the library manifest's credit fields.

Reads Heraldry/Library.lua (a Lua table of entries) with a small parser for the plain
table literals the manifest uses; nothing in it is executed. Run after adding icons:

  py tools\\credits.py           writes Heraldry\\CREDITS.md
  py tools\\credits.py --check   exits 1 if CREDITS.md is out of date (for CI)
"""

import argparse
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(REPO, "Heraldry", "Library.lua")
CREDITS = os.path.join(REPO, "Heraldry", "CREDITS.md")

# media/heraldry.tga, made by tools/gameicons2lib.py (BRAND there); not a library entry.
ADDON_ICON = ("`media/heraldry.tga` (the add-on list, minimap button and add-on drawer icon): \"Checked "
              "shield\" by Lorc, from game-icons.net, <https://game-icons.net/1x1/lorc/checked-shield.html>, "
              "CC-BY-3.0. Changes: tinted gold, black fill and outline added, resized.")

# Heraldry/IconNames.lua, made by tools/iconnames.py; data, not art, but credited all the same.
ICON_NAMES = ("`IconNames.lua` (names for the built-in game icons): labels made from World of Warcraft's icon "
              "file names, as collected by the community listfile, <https://github.com/wowdev/wow-listfile>. "
              "The file names are Blizzard Entertainment's; this file is not covered by Heraldry's MIT license.")

# Licenses that let the credit link to the license instead of shipping its text.
LICENSE_LINKS = {
    "CC-BY-3.0": "https://creativecommons.org/licenses/by/3.0/",
    "CC-BY-4.0": "https://creativecommons.org/licenses/by/4.0/",
    "CC0-1.0": "https://creativecommons.org/publicdomain/zero/1.0/",
}

TOKEN = re.compile(r"""
    (?P<space>\s+|--\[\[.*?\]\]|--[^\n]*)
  | (?P<string>"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')
  | (?P<number>-?\d+(?:\.\d+)?)
  | (?P<name>[A-Za-z_][A-Za-z0-9_]*)
  | (?P<punct>[{}=,;\[\]])
""", re.VERBOSE | re.DOTALL)


class ParseError(Exception):
    pass


def tokenize(text):
    position = 0
    while position < len(text):
        match = TOKEN.match(text, position)
        if not match:
            raise ParseError(f"unexpected {text[position:position + 20]!r}")
        position = match.end()
        kind = match.lastgroup
        if kind != "space":
            yield kind, match.group()


def unquote(literal):
    body = literal[1:-1]
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), body)


class Parser:
    def __init__(self, tokens):
        self.tokens = list(tokens)
        self.index = 0

    def peek(self):
        return self.tokens[self.index] if self.index < len(self.tokens) else (None, None)

    def take(self, value=None):
        token = self.peek()
        if value is not None and token[1] != value:
            raise ParseError(f"expected {value!r}, got {token[1]!r}")
        self.index += 1
        return token

    def value(self):
        kind, text = self.take()
        if kind == "string":
            return unquote(text)
        if kind == "number":
            return float(text) if "." in text else int(text)
        if kind == "name" and text in ("true", "false", "nil"):
            return {"true": True, "false": False, "nil": None}[text]
        if text == "{":
            self.index -= 1
            return self.table()
        raise ParseError(f"unexpected {text!r}")

    def table(self):
        self.take("{")
        items, fields = [], {}
        while self.peek()[1] != "}":
            kind, text = self.peek()
            following = self.tokens[self.index + 1][1] if self.index + 1 < len(self.tokens) else None
            if kind == "name" and following == "=":
                self.take()
                self.take("=")
                fields[text] = self.value()
            else:
                items.append(self.value())
            if self.peek()[1] in (",", ";"):
                self.take()
        self.take("}")
        return fields if fields else items


def read_manifest(path):
    with open(path, encoding="utf-8") as handle:
        text = handle.read()
    start = text.find("ns.LibraryManifest = {")
    if start < 0:
        raise ParseError("no 'ns.LibraryManifest = {' in " + path)
    parser = Parser(tokenize(text[start + len("ns.LibraryManifest = "):]))
    entries = parser.table()
    return entries if isinstance(entries, list) else []


def render(entries):
    lines = [
        "# Credits",
        "",
        "Art shipped with Heraldry and where it comes from. Generated by `tools/credits.py` from",
        "`Library.lua`; edit the manifest, not this file.",
        "",
        "## Heraldry's own icon",
        "",
        ADDON_ICON,
        "",
        "## Game icon names",
        "",
        ICON_NAMES,
        "",
        "## Library icons",
        "",
    ]
    used = {"CC-BY-3.0"}  # the add-on's own icon
    if not entries:
        lines.append("The library is empty in this version.")
        entries = []
    else:
        lines += ["| Icon | Source | Author | License | Changes | Link |", "|---|---|---|---|---|---|"]
    for entry in sorted(entries, key=lambda e: e["name"].lower()):
        credit = entry.get("credit", {})
        license_text = credit.get("license", "")
        used.add(license_text)
        if license_text == "permission":
            license_text = "Used with permission: " + credit.get("permission", "")
        link = credit.get("url", "")
        lines.append("| {} | {} | {} | {} | {} | {} |".format(
            entry["name"], credit.get("source", ""), credit.get("author", ""), license_text,
            credit.get("changes", ""), f"<{link}>" if link else ""))
    lines += [""]
    for spdx in sorted(used):
        if spdx in LICENSE_LINKS:
            lines.append(f"- {spdx}: <{LICENSE_LINKS[spdx]}>")
    lines += ["", "No author or source listed here endorses Heraldry. License texts not linked above are in",
              "`licenses/`."]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if CREDITS.md is out of date")
    args = parser.parse_args(argv)
    try:
        content = render(read_manifest(MANIFEST))
    except ParseError as error:
        print(f"credits: {error}", file=sys.stderr)
        return 1
    current = open(CREDITS, encoding="utf-8").read() if os.path.isfile(CREDITS) else None
    if args.check:
        if current != content:
            print("credits: CREDITS.md is out of date; run tools/credits.py", file=sys.stderr)
            return 1
        return 0
    with open(CREDITS, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
