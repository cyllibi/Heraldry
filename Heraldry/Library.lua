--[[ Library.lua
  The icon library manifest: icons shipped in media\library\. Icons.lua validates and
  indexes it at login; a bad entry is reported through the error handler and skipped.

  The game-icons.net set is one block in the table below, between its begin and end
  marker comments, rewritten as a whole by tools\gameicons2lib.py from
  tools\game-icons.txt: edit the list, not the block. Other entries are added with
  tools\emote2lib.py, which writes the texture and prints (or inserts) the entry. Fields:

    key        unique id, [a-z0-9_]. Stored in rules and export strings: never change it.
               To rename, add the old key to `aliases` of the new entry.
    name       display name in the picker
    file       texture path under media\library\, no extension ("game-icons/gi_checked_shield", "dev/dance")
    shape      "square" or "wide"
    width, height        art size in pixels (for animated icons: one frame)
    texWidth, texHeight  texture size in pixels, powers of two, at most 1024
    tags       optional list of search words
    anim       animated icons only: { cols =, rows =, frames =, fps = }
               Frames are packed left to right, top to bottom from the top-left corner,
               each width x height pixels; the sheet may be larger than the grid.
    thumb      animated icons only: { file =, texWidth =, texHeight = }, a static first
               frame for the picker grid (so browsing never loads whole sprite sheets)
    aliases    optional list of former keys
    credit     { source =, author =, license =, url =, permission =, changes = }
               source: where the art comes from ("7TV", "Fluent Emoji", ...); license: an
               SPDX id or "permission"; permission: who granted it and where, when the
               license is "permission"; changes: how the art was altered (licenses such
               as CC BY ask for it). tools\credits.py builds CREDITS.md from these.

  Development-only entries (test art that may not ship) live in a separate add-on,
  HeraldryDev, made by tools\emote2lib.py --dev: gitignored, never packaged, and read by
  Heraldry only when it is installed. ]]

