--[[ GameIcons.lua
  The built-in game icons: the list the macro icon picker shows, their names, and search.

  On Forever the macro icon functions return file IDs only; icon names are not available
  in game. IconNames.lua (generated by tools\iconnames.py) holds them instead:
    * the spell IDs of the player abilities that use each icon (class, rune, pet, talent,
      racial and poison spells from Forever's own data), every one of them, so an icon
      shared by two abilities is found by either. Their names come from the game
      (C_Spell.GetSpellName), so they are in the client's language.
    * a label made from every icon's file name, for icons no player ability uses
  It is parsed the first time a name is shown or searched (the picker, the options, the
  import preview, /heraldry check), never for nameplates, and released when the picker or
  an options page closes. Search is complete from the first keystroke; there is no
  background work. Known file IDs, texture paths, spell names the client knows and cached
  item names also work. ]]

local _, ns = ...

local GameIcons = {}
ns.GameIcons = GameIcons

local ICON_PATH_PREFIX = [[Interface\Icons\]]

local iconList       -- file IDs in macro picker order, built on first use
local inList = {}    -- file ID -> true
local looseNames = {} -- file ID -> raw file name, for loose macro icons

-- Parsed IconNames.lua, or nil until needed (see Names).
local names

local function AddIcon(list, value)
    local fileID = value
    if type(value) == "string" then
        -- The "loose" lists hold bare file names; try them as written and under Icons.
        local name = value:gsub("%.$", "")
        fileID = GetFileIDFromPath(name) or GetFileIDFromPath(ICON_PATH_PREFIX .. name)
        if fileID and not looseNames[fileID] then
            looseNames[fileID] = name:match("([^/\\]+)$")
        end
    end
    if fileID and not inList[fileID] then
        inList[fileID] = true
        list[#list + 1] = fileID
    end
end

-- Built directly rather than through IconDataProviderMixin, which shares its state with
-- Blizzard's macro window and collects every icon texture.
function GameIcons:GetList()
    if not iconList then
        local raw = {}
        GetLooseMacroIcons(raw)
        GetLooseMacroItemIcons(raw)
        GetMacroIcons(raw)
        GetMacroItemIcons(raw)
        iconList = {}
        for _, value in ipairs(raw) do
            AddIcon(iconList, value)
        end
    end
    return iconList
end

--------------------------------------------------------------------------------
-- Names
--------------------------------------------------------------------------------
-- " word word": folded, with hyphens as spaces, so search can match the start of each word.
local function Words(text)
    return " " .. ns.Identity.Fold(text):gsub("%-", " ")
end

-- "Name|Name" for "<spell ID>|<spell ID>": the game's own names, in the client's language.
-- Spells the client doesn't know drop out, as do repeated names.
local function AbilityNames(spellIDs)
    local found, seen = {}, {}
    local GetSpellName = C_Spell.GetSpellName
    if not GetSpellName then return nil end -- file labels still name the icon
    for spellID in spellIDs:gmatch("%d+") do
        local name = GetSpellName(tonumber(spellID))
        if name and name ~= "" and not seen[name] then
            seen[name] = true
            found[#found + 1] = name
        end
    end
    return #found > 0 and table.concat(found, "|") or nil
end

-- Parses IconNames.lua's "<delta> <label>[|<spell ID>|...]" lines (DESIGN.md has the cost):
--   abilities[fileID] "Ability|Ability", or nil
--   search[fileID]    " label words": the lower-case file label (if any) and every ability, for
--                     word-start search. For icons without abilities it is just " label", which
--                     doubles as the display label, so labels aren't stored twice.
--   spellIcons        icons player abilities use, in file ID order
local function Names()
    if not names then
        local abilities, search, spellIcons = {}, {}, {}
        local fileID = 0
        for delta, label, spellIDs in (ns.IconNamesData or ""):gmatch("(%d+) ([^|\n]*)|?([^\n]*)") do
            fileID = fileID + tonumber(delta)
            local text = label ~= "" and " " .. label or ""
            local spells = spellIDs ~= "" and AbilityNames(spellIDs)
            if spells then
                abilities[fileID] = spells
                spellIcons[#spellIcons + 1] = fileID
                text = text .. Words((spells:gsub("|", " ")))
            end
            if text ~= "" then search[fileID] = text end
        end
        names = { abilities = abilities, search = search, spellIcons = spellIcons }
    end
    return names
end

-- Called when the picker or an options page closes; the next name parses the data again.
function GameIcons:ReleaseNames()
    names = nil
end

-- For tests and diagnostics: whether the names are parsed right now.
function GameIcons:HasNames()
    return names ~= nil
end

-- The first player ability that uses the icon, else its file label, else a loose macro
-- icon's raw file name. nil for icons nobody names.
function GameIcons:GetIconName(fileID)
    local data = Names()
    local abilities = data.abilities[fileID]
    if abilities then return abilities:match("^[^|]+") end
    local label = data.search[fileID] -- just " label" for icons without abilities
    if label and label ~= "" then return (label:gsub("^ (%l?)", string.upper)) end
    return looseNames[fileID]
end

-- The other player abilities that use the icon, comma-separated, or nil.
function GameIcons:GetOtherNames(fileID)
    local abilities = Names().abilities[fileID]
    local others = abilities and abilities:match("^[^|]+|(.+)$")
    return others and (others:gsub("|", ", "))
end

-- True when fileID is an icon Heraldry knows about, not just any number.
function GameIcons:IsKnownIcon(fileID)
    self:GetList()
    return inList[fileID] or Names().search[fileID] ~= nil
end

--------------------------------------------------------------------------------
-- Search
--------------------------------------------------------------------------------
local function AddUnique(results, seen, fileID)
    if fileID and not seen[fileID] then
        seen[fileID] = true
        results[#results + 1] = fileID
    end
end

-- Returns a list of file IDs. An empty query returns the whole list.
function GameIcons:Search(query)
    local list = self:GetList()
    query = ns.Trim(query or "")
    if query == "" then return list end

    local results, seen = {}, {}
    if query:match("^%d+$") then
        -- Only a real icon: any other number would show the missing-texture square.
        local fileID = tonumber(query)
        if self:IsKnownIcon(fileID) then AddUnique(results, seen, fileID) end
        return results
    end
    if query:find("[/\\]") then
        AddUnique(results, seen, GetFileIDFromPath(query) or GetFileIDFromPath(ICON_PATH_PREFIX .. query))
        return results
    end

    -- Exact names first: a spell the client knows (in its own language), a cached item.
    AddUnique(results, seen, C_Spell.GetSpellTexture(query))
    AddUnique(results, seen, select(5, C_Item.GetItemInfoInstant(query)))

    -- Then every icon whose abilities or file label have a word starting with each query
    -- word, as in the library ("ice" finds Ice Barrier, not Sacrifice).
    local words = {}
    for word in Words(query):gmatch("[^ ]+") do words[#words + 1] = " " .. word end
    local search = Names().search
    local function HasWords(text)
        if not text then return false end
        for _, word in ipairs(words) do
            if not text:find(word, 1, true) then return false end
        end
        return true
    end
    local function Match(fileID)
        local text = search[fileID]
        if text then return HasWords(text) end
        -- A loose macro icon the data doesn't name: its raw file name, underscores as spaces.
        local loose = looseNames[fileID]
        return loose ~= nil and HasWords(Words((loose:gsub("_", " "))))
    end
    for _, fileID in ipairs(list) do
        if Match(fileID) then AddUnique(results, seen, fileID) end
    end
    -- Ability icons the macro list lacks.
    for _, fileID in ipairs(Names().spellIcons) do
        if not inList[fileID] and Match(fileID) then AddUnique(results, seen, fileID) end
    end
    return results
end
